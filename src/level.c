// Simple function to get block at coordinates (for testing)
uint8_t getBlockAt(const uint8_t level[], uint8_t x, uint8_t y) {
    if (x < 0 || x >= LEVEL_WIDTH || y < 0 || y >= LEVEL_HEIGHT) {
        return E_FLOOR;
    }

    // y is read in inverse order for the original layout
    // This is a simplified version - in a real implementation we would properly 
    // decode the 2-bit per cell level data
    if (x == 0 || x == LEVEL_WIDTH-1 || y == 0 || y == LEVEL_HEIGHT-1) {
        return E_WALL; // Border walls
    }
    
    // Simple maze pattern
    if ((x > 10 && x < 20 && y > 5 && y < 15) || 
        (x > 30 && x < 40 && y > 15 && y < 25)) {
        return E_WALL;
    }
    
    // Player spawn position
    if (x == 20 && y == 10) {
        return E_PLAYER;
    }
    
    return E_FLOOR; // Default to floor
}